#!/usr/bin/env python3
"""Splits the golden snapshots (snapshots/<state>-dark.html) into page fragments:
assets/fragments/<state>.main.html (inner HTML of main[data-slot=sidebar-inset]) and
<state>.overlay.html (portal siblings after the app root: dialogs, palettes, toasts), and writes
src/ui/fragments.rs with an include_str! table. Re-run after re-exporting the goldens."""
import lxml.html, os, re, sys
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SNAP = os.path.join(ROOT, 'snapshots'); OUT = os.path.join(ROOT, 'assets', 'fragments')
os.makedirs(OUT, exist_ok=True)
SKIP = {'thread-history', 'thread-question'}
def inner(e):
    s = (e.text or '').replace('&', '&amp;').replace('<', '&lt;')
    return s + ''.join(lxml.html.tostring(c, encoding='unicode') for c in e)
def outer(e): return lxml.html.tostring(e, encoding='unicode')
NORM = re.compile(r' (id|aria-controls|aria-labelledby|data-id)="[^"]*"')
def norm(x): return NORM.sub('', x)
def is_empty_toast(k):
    if k.get('data-slot') not in ('toast-portal', 'toast-portal-anchored'): return False
    return not any(len(v) for v in k.xpath('.//*[@data-slot="toast-viewport" or @data-slot="toast-viewport-anchored"]'))
def parts(path):
    body = lxml.html.parse(path).getroot().body
    mains = body.xpath('.//main[@data-slot="sidebar-inset"]')
    main = inner(mains[0]) if mains else ''
    kids = [k for k in body if isinstance(k.tag, str)]
    rest = [outer(k) for k in kids[2:] if not is_empty_toast(k)]
    # Dialogs of routes come before the toast portals, popups of the chat views after them.
    toasts = [i for i, k in enumerate(kids[2:]) if k.get('data-slot') in ('toast-portal', 'toast-portal-anchored')]
    others = [i for i, k in enumerate(kids[2:]) if not is_empty_toast(k) and k.get('data-slot') not in ('toast-portal', 'toast-portal-anchored')]
    after = bool(toasts and others and min(others) > min(toasts))
    return main, rest, after
base_main, base_rest, _ = parts(os.path.join(SNAP, 'new-chat-dark.html'))
names = sorted(f[:-10] for f in os.listdir(SNAP) if f.endswith('-dark.html'))
rows = []
for n in names:
    if n in SKIP: continue
    main, rest, after = parts(os.path.join(SNAP, n + '-dark.html'))
    overlay = ''.join(rest)
    has_main = 'data-chat-column' not in main
    if has_main: open(os.path.join(OUT, n + '.main.html'), 'w').write(main)
    if overlay: open(os.path.join(OUT, n + '.overlay.html'), 'w').write(overlay)
    rows.append((n, has_main, bool(overlay), after))
with open(os.path.join(ROOT, 'src', 'ui', 'fragments.rs'), 'w') as f:
    f.write('//! Generated by tools/extract_fragments.py: page fragments from the golden snapshots.\n')
    f.write('pub struct Page { pub name: &\'static str, pub main: Option<&\'static str>, pub overlay: Option<&\'static str>, pub overlay_after_toasts: bool }\n\n')
    f.write('pub const PAGES: &[Page] = &[\n')
    for n, m, o, a in rows:
        mm = f'Some(include_str!("../../assets/fragments/{n}.main.html"))' if m else 'None'
        oo = f'Some(include_str!("../../assets/fragments/{n}.overlay.html"))' if o else 'None'
        f.write(f'    Page {{ name: "{n}", main: {mm}, overlay: {oo}, overlay_after_toasts: {str(a).lower()} }},\n')
    f.write('];\n\npub fn page(name: &str) -> Option<&\'static Page> {\n    PAGES.iter().find(|p| p.name == name)\n}\n')
print(len(rows), 'pages')
for r in rows: print(r)
