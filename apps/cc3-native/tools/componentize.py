#!/usr/bin/env python3
"""Turns repeated subtrees of a golden XHTML snapshot into Rust/Dioxus components.
Instances of one component must have the same element skeleton; every text or attribute value that
differs between instances becomes a `String` prop (named by NAMES, else p0, p1, ...).
Usage: componentize.py <body.xml> <out_dir> ; edit COMPONENTS below to add components."""
import sys, os, re, copy
import xml.etree.ElementTree as ET

def local(t): return t.split('}')[-1]
def rs(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n') + '"'
def lit(s):  # text for rsx with braces escaped
    return rs(s.replace('{', '{{').replace('}', '}}'))
IDENT = re.compile(r'^[a-zA-Z][a-zA-Z0-9_]*$')

# name -> (predicate on element, {param index: name})
COMPONENTS = {
    "ThreadRow": (lambda e: local(e.tag) == 'li' and e.attrib.get('class', '').startswith('list-none py-0.5'), {}),
}

def skeleton(e):
    return (local(e.tag), tuple(sorted(e.attrib)), tuple(skeleton(c) for c in e), bool((e.text or '').strip()), bool((e.tail or '').strip()))

def leaves(e, path=()):
    """Yield (path, kind, key, value) for every text / attribute value."""
    for k, v in sorted(e.attrib.items()):
        yield (path, 'attr', k, v)
    if (e.text or '').strip(): yield (path, 'text', None, e.text)
    for i, c in enumerate(e):
        yield from leaves(c, path + (i,))
        if (c.tail or '').strip(): yield (path + (i,), 'tail', None, c.tail)

def get(e, path):
    for i in path: e = e[i]
    return e

def emit(e, depth, out, params, path=()):
    pad = '    ' * depth
    tag = local(e.tag)
    name = tag if IDENT.match(tag) else tag.lower()
    a = []
    for k, v in e.attrib.items():
        k = local(k) if k.startswith('{') else k
        if k.startswith('xmlns'): continue
        key = (path, 'attr', k)
        a.append(f'{rs(k)}: {("{" + params[key] + "}") if key in params else lit(v)}'.replace('{' + params.get(key, '') + '}', f'"{{{params[key]}}}"') if key in params else f'{rs(k)}: {lit(v)}')
    kids = list(e)
    text = e.text or ''
    tkey = (path, 'text', None)
    texts = []
    if tkey in params: texts.append(f'"{{{params[tkey]}}}"')
    elif text.strip(): texts.append(lit(text))
    if not a and not kids and not texts:
        out.append(f'{pad}{name} {{ }}'); return
    out.append(f'{pad}{name} {{')
    for x in a: out.append(f'{pad}    {x},')
    for t in texts: out.append(f'{pad}    {t}')
    for i, kid in enumerate(kids):
        emit(kid, depth + 1, out, params, path + (i,))
        k2 = (path + (i,), 'tail', None)
        if k2 in params: out.append(f'{pad}    "{{{params[k2]}}}"')
        elif (kid.tail or '').strip(): out.append(f'{pad}    {lit(kid.tail)}')
    out.append(f'{pad}}}')

def main():
    tree = ET.parse(sys.argv[1]).getroot()
    out_dir = sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    for cname, (pred, names) in COMPONENTS.items():
        inst = [e for e in tree.iter() if pred(e)]
        if not inst: print('no instances for', cname); continue
        sk = skeleton(inst[0])
        same = [i for i in inst if skeleton(i) == sk]
        print(cname, len(inst), 'instances,', len(same), 'with equal skeleton')
        base = list(leaves(same[0]))
        params = {}
        order = []
        for idx, (path, kind, key, v) in enumerate(base):
            vals = [list(leaves(i))[idx][3] for i in same]
            if len(set(vals)) > 1:
                n = names.get(len(order)) or f'p{len(order)}'
                params[(path, kind, key)] = n
                order.append((n, kind, key, path))
        lines = []
        emit(same[0], 2, lines, params)
        fields = ', '.join(f'{n}: String' for n, *_ in order)
        body = '\n'.join(lines)
        code = f'//! GENERATED by tools/componentize.py (then edited by hand).\nuse dioxus::prelude::*;\n\n#[component]\npub fn {cname}({fields}) -> Element {{\n    rsx! {{\n{body}\n    }}\n}}\n'
        fn = re.sub(r'(?<!^)(?=[A-Z])', '_', cname).lower()
        open(os.path.join(out_dir, fn + '.rs'), 'w').write(code)
        print(' params:', [(n, kind, key) for n, kind, key, _ in order])
        for i in same:
            vals = [list(leaves(i))[idx][3] for idx, (p, k, key, v) in enumerate(base) if (p, k, key) in params]
            print(' instance values:', [v[:40] for v in vals])
main()
